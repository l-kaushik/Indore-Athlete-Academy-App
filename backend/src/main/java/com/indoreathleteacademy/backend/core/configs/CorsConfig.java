package com.indoreathleteacademy.backend.core.configs;

import org.springframework.beans.factory.annotation.Value;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;
import org.springframework.web.cors.CorsConfiguration;
import org.springframework.web.cors.CorsConfigurationSource;
import org.springframework.web.cors.UrlBasedCorsConfigurationSource;

import java.util.List;

@Configuration
public class CorsConfig {
    private final String corsPrimaryUrl;
    private final String corsSecondaryUrl;
    public CorsConfig(@Value("${cors.primary-url}") String corsPrimaryUrl,
                      @Value("${cors.secondary-url}") String corsSecondaryUrl) {
        this.corsPrimaryUrl = corsPrimaryUrl;
        this.corsSecondaryUrl = corsSecondaryUrl;
    }

    @Bean
    public CorsConfigurationSource corsConfigurationSource() {
        CorsConfiguration configuration = new CorsConfiguration();

        configuration.setAllowedOrigins(List.of(
                corsPrimaryUrl, corsSecondaryUrl
        ));

        configuration.setAllowedMethods(List.of(
                "GET", "POST", "PUT", "DELETE", "OPTIONS"
        ));

        configuration.setAllowedHeaders(List.of("*"));

        configuration.setAllowCredentials(true);

        UrlBasedCorsConfigurationSource source =
                new UrlBasedCorsConfigurationSource();

        source.registerCorsConfiguration("/**", configuration);

        return source;
    }
}
